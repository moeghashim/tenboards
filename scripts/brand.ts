import config from "../tenboards.config.ts";
import { derive } from "./brand/derive.ts";
import { readFile, writeFile } from "node:fs/promises";
import { parseArgs } from "node:util";

try {
  const { values, positionals } = parseArgs({
    options: { reset: { type: "boolean" }, check: { type: "boolean" }, exact: { type: "boolean" } },
    allowPositionals: true,
  });
  if (
    positionals.length > 1 ||
    (values.reset && (positionals.length || values.exact || values.check)) ||
    (values.check && positionals.length)
  )
    throw new Error("Use brand <color> [--exact], brand --reset, or brand --check.");
  const input = values.reset ? undefined : (positionals[0] ?? config.brand.color);
  const exact = values.reset ? false : (values.exact ?? config.brand.exact ?? false);
  let output = "/* Generated by npm run brand. Do not edit; configure tenboards.config.ts. */\n";
  if (input === undefined) output += await readFile(new URL("./brand/default.css", import.meta.url), "utf8");
  else {
    const { modes, reports } = derive(input, exact);
    // Specificity beats shared aliases without relying on import order.
    for (const [mode, roles] of Object.entries(modes))
      output += `:root:root:root${mode === "dark" ? ".dark" : ":not(.dark)"} {\n${Object.entries(roles)
        .map(([k, v]) => `  --${k}: ${v};`)
        .join("\n")}\n}\n`;
    // Tailwind merges custom and built-in utilities; priority keeps its fill alias from winning.
    output +=
      "@utility border-primary { border-color: var(--action-accent) !important; }\n@utility ring-primary { --tw-ring-color: var(--ring) !important; }\n";
    console.log(reports.join("\n"));
  }
  if (values.check) {
    if ((await readFile("src/styles/brand.css", "utf8")) !== output)
      throw new Error("Stale src/styles/brand.css; run npm run brand.");
    console.log("PASS brand freshness");
  } else {
    if (positionals.length || values.reset) {
      const source = await readFile("tenboards.config.ts", "utf8");
      const updated = source
        .replace(
          /(\bcolor:\s*)(undefined|"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*')/,
          (_, prefix) => prefix + (input === undefined ? "undefined" : JSON.stringify(input)),
        )
        .replace(/(\bexact:\s*)(true|false)/, `$1${exact}`);
      if (updated === source && input !== config.brand.color)
        throw new Error("Cannot locate brand.color literal in tenboards.config.ts; edit it manually.");
      await writeFile("tenboards.config.ts", updated);
    }
    await writeFile("src/styles/brand.css", output);
    console.log(input === undefined ? "Brand unset: original themes restored." : "Generated src/styles/brand.css");
  }
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
}
